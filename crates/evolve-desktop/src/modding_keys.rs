//! Resolve only the configured private-manager stage's existing signing files.
//! No embedded key material, broad disk search or implicit key generation.
use std::fs;
use std::path::{Path, PathBuf};

#[derive(Clone, Debug)]
pub struct KeyContext {
    pub original_public: PathBuf,
    pub public: PathBuf,
    pub private: PathBuf,
}

fn regular(path: &Path) -> bool {
    fs::symlink_metadata(path)
        .is_ok_and(|m| m.file_type().is_file() && m.len() > 0 && m.len() <= 64 * 1024)
}

/// Public-only original Stage 2 verification key; no private signing material.
const ORIGINAL_PUBLIC_RSA: &[u8; 140] = include_bytes!("../../../assets/reference/RSAKeyData.bin");

pub struct ArchiveVerificationKeys {
    pub paths: Vec<PathBuf>,
    _bundled_key_directory: tempfile::TempDir,
}

/// Each archive's decrypted CDR and signature determine which key is valid.
/// The temporary embedded public-key file remains alive until import completes.
pub fn archive_verification_keys(stage: &Path) -> Result<ArchiveVerificationKeys, String> {
    let mut paths = Vec::new();
    for candidate in [original_public_key(stage).ok(), public_key(stage).ok()]
        .into_iter()
        .flatten()
    {
        if !paths.contains(&candidate) {
            paths.push(candidate);
        }
    }
    let directory = tempfile::Builder::new()
        .prefix("evolve-original-public-rsa-")
        .tempdir()
        .map_err(|e| format!("Cannot prepare bundled RSA verification key: {e}"))?;
    let bundled = directory.path().join("RSAKeyData.bin");
    fs::write(&bundled, ORIGINAL_PUBLIC_RSA)
        .map_err(|e| format!("Cannot write bundled RSA verification key: {e}"))?;
    paths.push(bundled);
    Ok(ArchiveVerificationKeys {
        paths,
        _bundled_key_directory: directory,
    })
}

pub fn public_key(stage: &Path) -> Result<PathBuf, String> {
    let key = stage.join("mykeys").join("public_key.bin");
    if !regular(&key) {
        return Err(format!(
            "The configured signing stage has no public key at {}. \
             Complete the existing private manager's signing-stage setup first.",
            key.display()
        ));
    }
    Ok(key)
}

/// Exact original Stage 2 signing key used by the private manager's
/// CustomSigning stage. Never substitute a custom signing key when an original
/// game PAK has not been cryptographically verified.
pub fn original_public_key(stage: &Path) -> Result<PathBuf, String> {
    let parent = stage
        .parent()
        .ok_or("Configured signing stage has no parent directory")?;
    let key = parent.join("RSAKeyData.bin");
    if !fs::symlink_metadata(&key).is_ok_and(|m| m.file_type().is_file() && m.len() == 140) {
        return Err(format!(
            "Original 140-byte RSAKeyData.bin missing from {}.              The original Stage 2 PAK cannot be re-signed safely without its exact public key.",
            parent.display()
        ));
    }
    Ok(key)
}

/// Select either the verified original or the stage's custom key from the
/// authenticated archive signature, never from its filename or folder.
/// Original archives and already-custom-signed archives use different keys.
pub fn verified_archive_key(
    stage: &Path,
    source: &Path,
    signed_basename: &str,
) -> Result<PathBuf, String> {
    let original = original_public_key(stage).ok();
    let custom = public_key(stage).ok();
    for candidate in [original, custom].into_iter().flatten() {
        if evolve_core::inspect_signed_pak(source, &candidate, signed_basename).is_ok() {
            return Ok(candidate);
        }
    }
    Err("Archive cannot be authenticated with the original or configured custom Stage 2 RSA key; source/key/basename mismatch.".into())
}

pub fn signing_keys(stage: &Path) -> Result<KeyContext, String> {
    let original_public = original_public_key(stage)?;
    let public = public_key(stage)?;
    let private = stage.join("mykeys").join("private_key.pem");
    if !regular(&private) {
        return Err(format!(
            "The stage's local private signing key is missing at {}. \
             No private signing key is bundled or generated by the Rust manager.",
            private.display()
        ));
    }
    Ok(KeyContext {
        original_public,
        public,
        private,
    })
}

/// Signed CryPAK basename is the actual file name; never a user-entered guess.
/// Reject directories or names which could escape a staging path.
pub fn signed_basename(path: &Path) -> Result<String, String> {
    let name = path
        .file_name()
        .and_then(|s| s.to_str())
        .ok_or("Choose a named .pak archive")?;
    if !name.to_ascii_lowercase().ends_with(".pak")
        || name.len() > 240
        || name.contains('/')
        || name.contains('\\')
        || name == "."
        || name == ".."
    {
        return Err("Choose an actual .pak archive filename".into());
    }
    Ok(name.to_owned())
}

/// Only a selected regular file **inside** stage/paks can set the target.
/// Never choose a replacement target by matching its basename alone.
pub fn staged_target(stage: &Path, source: &Path) -> Result<String, String> {
    let root = fs::canonicalize(stage.join("paks"))
        .map_err(|_| "Configure a prepared signing stage with a paks/ directory")?;
    let metadata =
        fs::symlink_metadata(source).map_err(|_| "Choose an existing staged original PAK")?;
    if !metadata.file_type().is_file() {
        return Err("A staged PAK must be an actual regular file".into());
    }
    let chosen = fs::canonicalize(source).map_err(|_| "Cannot resolve the staged PAK")?;
    let relative = chosen.strip_prefix(&root)
        .map_err(|_| "The chosen PAK is not inside the configured stage/paks; select its exact staged original")?;
    let label = relative.to_string_lossy().replace('\\', "/");
    // Validate against the same allowed member path policy as the core.
    if !label.to_ascii_lowercase().ends_with(".pak")
        || label
            .split('/')
            .any(|piece| piece.is_empty() || piece == "." || piece == "..")
    {
        return Err("Invalid staged target path".into());
    }
    Ok(label)
}

/// Materialize one authenticated stock PAK only when an enabled Mod Project
/// needs it. Sparse setups intentionally have NO full-game staging copy.
/// Never modify installed PAKs; publish one verified file atomically.
pub fn ensure_selected_stage_pak(stage: &Path, relative: &str) -> Result<(), String> {
    use evolve_core::signed_pak::{
        inspect_signed_pak, resign_signed_pak_with_original_name,
    };
    use sha2::{Digest, Sha256};
    if !relative.to_ascii_lowercase().ends_with(".pak")
        || relative.split('/').any(|p| p.is_empty() || p == "." || p == ".." || p.contains('\\') || p.contains(':'))
        || relative.starts_with('/')
    {
        return Err("Unsafe selected PAK path".into());
    }
    let stage = fs::canonicalize(stage).map_err(|e| format!("Invalid signing stage: {e}"))?;
    let status: serde_json::Value =
        serde_json::from_slice(&fs::read(stage.join("stage_status.json")).map_err(|e| e.to_string())?)
            .map_err(|e| format!("Invalid signing status: {e}"))?;
    let plan: serde_json::Value =
        serde_json::from_slice(&fs::read(stage.join("rekey_plan.json")).map_err(|e| e.to_string())?)
            .map_err(|e| format!("Invalid signing inventory: {e}"))?;
    let entry = plan["entries"].as_array()
        .and_then(|rows| rows.iter().find(|item| item["path"].as_str() == Some(relative)
            && item["kind"].as_str() == Some("signed-encrypted")))
        .ok_or("Selected PAK is not in this game's verified signing inventory")?;
    let root = fs::canonicalize(plan["source_root"].as_str()
        .ok_or("Signing inventory has no source game root")?)
        .map_err(|e| format!("Signing inventory's game is missing: {e}"))?;
    if root.starts_with(&stage) || stage.starts_with(&root) {
        return Err("Game and signing stage must not overlap".into());
    }
    let original = root.join(relative);
    if !fs::symlink_metadata(&original).is_ok_and(|m| m.file_type().is_file())
        || !fs::canonicalize(&original).is_ok_and(|path| path.starts_with(&root))
    {
        return Err(format!("Missing, linked or unsafe original game PAK: {relative}"));
    }
    let source_sha = entry["sha256"].as_str().ok_or("Missing original PAK digest")?;
    if source_sha.len() != 64 || !source_sha.bytes().all(|c| c.is_ascii_hexdigit()) {
        return Err("Invalid pinned game PAK SHA-256".into());
    }
    fn digest(path: &Path) -> Result<String, String> {
        use std::io::Read;
        let mut f = fs::File::open(path).map_err(|e| e.to_string())?;
        let mut hasher = Sha256::new();
        let mut buf = [0u8; 256 * 1024];
        loop {
            let n = f.read(&mut buf).map_err(|e| e.to_string())?;
            if n == 0 { break; }
            hasher.update(&buf[..n]);
        }
        Ok(format!("{:x}", hasher.finalize()))
    }
    if !digest(&original)?.eq_ignore_ascii_case(source_sha) {
        return Err(format!("Original game PAK has changed since setup: {relative}"));
    }
    let basename = signed_basename(&original)?;
    let signed_name = entry["signed_name"].as_str().unwrap_or(&basename);
    if signed_name != basename && signed_name != basename.to_ascii_lowercase() {
        return Err("Untrusted authenticated PAK basename".into());
    }
    let original_key = original_public_key(&stage)?;
    let custom_key = public_key(&stage)?;
    inspect_signed_pak(&original, &original_key, signed_name)
        .map_err(|e| format!("Installed original PAK signature failed: {e}"))?;
    let paks = fs::canonicalize(stage.join("paks"))
        .map_err(|e| format!("Signing stage has no paks directory: {e}"))?;
    let target = paks.join(relative);
    if let Ok(meta) = fs::symlink_metadata(&target) {
        if !meta.file_type().is_file()
            || !fs::canonicalize(&target).is_ok_and(|path| path.starts_with(&paks))
        {
            return Err("Existing selected stage target is not a safe regular file".into());
        }
        inspect_signed_pak(&target, &custom_key, signed_name)
            .map_err(|e| format!("Existing selected stage PAK failed signature: {e}"))?;
        return Ok(());
    }
    // Existing full stages can also recover one missing original when the
    // immutable inventory and installed signature still authenticate it.
    // The stage must be idle; caller restores prior profile before provisioning.
    if status["status"].as_str() != Some("fully-staged-offline") {
        return Err("Signing stage is not ready for selected-PAK repair".into());
    }
    let parent = target.parent().ok_or("Selected PAK lacks parent")?;
    fs::create_dir_all(parent).map_err(|e| e.to_string())?;
    // Only manager-created, non-linked stage folders may receive a PAK.
    let canonical_parent = fs::canonicalize(parent).map_err(|e| e.to_string())?;
    if !canonical_parent.starts_with(&paks) {
        return Err("Selected stage destination escaped signing workspace".into());
    }
    let temp = tempfile::Builder::new()
        .prefix(".selected-pak-")
        .tempdir_in(parent)
        .map_err(|e| e.to_string())?;
    let output = temp.path().join(&basename);
    if fs::read(&original_key).map_err(|e| e.to_string())?
        == fs::read(&custom_key).map_err(|e| e.to_string())?
    {
        // Supplied original developer key: stock PAK already authenticates.
        // Copy ONLY this selected archive, with no mass re-signing.
        fs::copy(&original, &output).map_err(|e| e.to_string())?;
    } else if let Some(official) = crate::official_stage2_tools::for_stage(&stage)? {
        official.rekey_copy(&original, signed_name, &output)?;
    } else {
        let keys = signing_keys(&stage)?;
        resign_signed_pak_with_original_name(
            &original, &original_key, &keys.private, &custom_key,
            signed_name, &basename, &output,
        ).map_err(|e| format!("Cannot sign selected PAK {relative}: {e}"))?;
    }
    inspect_signed_pak(&output, &custom_key, signed_name)
        .map_err(|e| format!("Selected PAK failed signing verification: {e}"))?;
    if !digest(&original)?.eq_ignore_ascii_case(source_sha) {
        return Err("Original game PAK changed during selected signing".into());
    }
    // hard_link publishes without overwriting anything even if another
    // process unexpectedly creates the target while the copy is prepared.
    fs::hard_link(&output, &target)
        .map_err(|e| format!("Cannot publish selected PAK without overwrite: {e}"))?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn selecting_unknown_or_unsafe_sparse_targets_never_creates_game_copies() {
        let tmp = tempfile::tempdir().unwrap();
        let stage = tmp.path().join("stage");
        fs::create_dir(&stage).unwrap();
        fs::create_dir(stage.join("paks")).unwrap();
        for invalid in ["Game/../other.pak", "Game\\other.pak", "../other.pak", "a.txt"] {
            assert!(ensure_selected_stage_pak(&stage, invalid).is_err());
        }
        assert!(ensure_selected_stage_pak(&stage, "Game/UI_Assets.pak").is_err());
        assert_eq!(fs::read_dir(stage.join("paks")).unwrap().count(), 0);
    }

    #[test]
    fn bundled_original_key_is_tried_even_after_mismatched_local_keys() {
        let root = tempfile::tempdir().unwrap();
        let stage = root.path().join("stage");
        let key_folder = stage.join("mykeys");
        fs::create_dir_all(&key_folder).unwrap();
        let custom = key_folder.join("public_key.bin");
        fs::write(&custom, b"custom key").unwrap();
        let misleading_original = root.path().join("RSAKeyData.bin");
        fs::write(&misleading_original, [0u8; 140]).unwrap();
        let candidates = archive_verification_keys(&stage).unwrap();
        assert_eq!(candidates.paths.len(), 3);
        assert_eq!(candidates.paths[0], misleading_original);
        assert_eq!(candidates.paths[1], custom);
        assert_eq!(
            fs::read(candidates.paths.last().unwrap()).unwrap(),
            ORIGINAL_PUBLIC_RSA
        );
    }

    #[test]
    fn bundled_original_key_requires_no_existing_stage() {
        let root = tempfile::tempdir().unwrap();
        let candidates = archive_verification_keys(&root.path().join("missing")).unwrap();
        assert_eq!(candidates.paths.len(), 1);
        assert_eq!(fs::read(&candidates.paths[0]).unwrap().len(), 140);
    }

    #[test]
    fn derives_keys_from_selected_stage_without_keys_in_settings() {
        let root = tempfile::tempdir().unwrap();
        let stage = root.path().join("staged");
        fs::create_dir(&stage).unwrap();
        let keys = stage.join("mykeys");
        fs::create_dir(&keys).unwrap();
        fs::write(keys.join("public_key.bin"), b"test-public-only").unwrap();
        assert!(public_key(&stage).is_ok());
        assert!(signing_keys(&stage).is_err());
        fs::write(keys.join("private_key.pem"), b"test-key").unwrap();
        assert!(
            signing_keys(&stage).is_err(),
            "original RSA key cannot default to custom"
        );
        fs::write(root.path().join("RSAKeyData.bin"), [0u8; 140]).unwrap();
        assert!(signing_keys(&stage).is_ok());
        fs::create_dir(stage.join("paks")).unwrap();
        fs::write(stage.join("paks").join("libs.pak"), b"fake").unwrap();
        assert_eq!(
            staged_target(&stage, &stage.join("paks/libs.pak")).unwrap(),
            "libs.pak"
        );
        assert!(staged_target(&stage, &keys.join("public_key.bin")).is_err());
    }
}
